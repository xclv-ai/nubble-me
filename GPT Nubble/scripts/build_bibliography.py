"""Build citation artifacts from the two curated primary-source ledgers."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]


def load_sources():
    result = []
    for filename, field in [("related-work-sources.json", "sources"), ("evaluation-sources.json", "records")]:
        data = json.loads((ROOT / "research" / filename).read_text())
        for item in data[field]:
            result.append({
                "id": item["id"], "title": item["title"],
                "authors": item["authors"], "year": item["year"],
                "venue": item.get("venue", ""), "doi": item.get("doi"),
                "url": item.get("canonical_url") or item["url"],
                "version_read": item.get("version_read", ""),
                "access_level": item.get("access_level", ""),
                "evidence_ledger": filename,
            })
    assert len({item["id"] for item in result}) == len(result), "Duplicate source IDs"
    return result


def bib_escape(text):
    return str(text).replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%")


def build():
    sources = load_sources()
    bib = ["% Generated by scripts/build_bibliography.py. Metadata facts; linked works retain their own rights."]
    for item in sources:
        fields = {
            "title": "{" + item["title"] + "}",
            "author": " and ".join(item["authors"]), "year": item["year"],
            "howpublished": item["venue"], "url": item["url"],
            "note": "Version and partial-access limits: research/" + item["evidence_ledger"],
        }
        if item["doi"]:
            fields["doi"] = item["doi"]
        bib.append("@misc{" + item["id"] + ",\n" + ",\n".join(
            "  " + key + " = {" + bib_escape(value) + "}" for key, value in fields.items()) + "\n}")
    (ROOT / "paper" / "references.bib").write_text("\n\n".join(bib) + "\n")
    (ROOT / "research" / "sources.json").write_text(json.dumps({
        "schema_version": "0.2", "research_date": "2026-10-25",
        "scope": "Focused, non-exhaustive primary-source review. Access level does not imply whole-paper reading.",
        "source_count": len(sources), "sources": sources,
    }, ensure_ascii=False, indent=2) + "\n")
    refs = ["# References\n", "Generated from the curated source ledgers. Full access/version limitations remain in those ledgers.\n"]
    for number, item in enumerate(sources, 1):
        refs.append(f"{number}. {', '.join(item['authors'])}. {item['year']}. **{item['title']}**. {item['venue']}. [Canonical record]({item['url']}).")
    (ROOT / "paper" / "REFERENCES.md").write_text("\n\n".join(refs) + "\n")
    print(f"Built BibTeX, source index, and reference list for {len(sources)} studies.")


if __name__ == "__main__":
    build()
