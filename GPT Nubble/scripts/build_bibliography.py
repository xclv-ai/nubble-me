"""Build scholarly references from the three curated primary-source ledgers."""
from pathlib import Path
import json
import unicodedata

ROOT = Path(__file__).resolve().parents[1]


def load_sources():
    result = []
    for filename, field in [('related-work-sources.json', 'sources'), ('evaluation-sources.json', 'records'), ('foundations-sources.json', 'sources')]:
        for item in json.loads((ROOT / 'research' / filename).read_text())[field]:
            result.append({
                'id': item['id'], 'title': item['title'], 'authors': item['authors'],
                'year': item['year'], 'venue': item.get('venue', ''), 'doi': item.get('doi'),
                'pages': item.get('pages'), 'url': item.get('canonical_url') or item.get('url'),
                'version_read': item.get('version_read', ''), 'access_level': item.get('access_level', ''),
                'evidence_ledger': filename,
            })
    assert len({x['id'] for x in result}) == len(result), 'Duplicate source IDs'
    return result


def bib_escape(value):
    replacements = {'&': r'\&', '%': r'\%', '_': r'\_', '#': r'\#', '–': '--', '—': '---', '’': "'"}
    accents = {'\u0308': '"', '\u0327': 'c', '\u0301': "'", '\u0300': '`', '\u0302': '^', '\u0303': '~'}
    output = ''
    for ch in str(value):
        decomposed = unicodedata.normalize('NFD', ch)
        if len(decomposed) == 2 and decomposed[1] in accents:
            output += '{\\' + accents[decomposed[1]] + '{' + decomposed[0] + '}}'
        else:
            output += replacements.get(ch, ch)
    return output


def bib_entry(item):
    key, venue = item['id'], item['venue']
    fields = {'title': '{' + bib_escape(item['title']) + '}',
              'author': bib_escape(' and '.join(item['authors'])), 'year': str(item['year'])}
    if key == 'spinoso_cheung_2024_rsa':
        fields['author'] = 'Spinoso-Di Piano, Cesare and Cheung, Jackie Chi Kit'
    kind = 'inproceedings'
    if key in {'ghodratnama_zakershahrak_2024_sumrecom', 'spinoso_cheung_2024_rsa', 'zhang_chen_2025_financial_cot', 'li_chaturvedi_2025_compsum', 'cachola_etal_2026_information_satisfaction'}:
        kind = 'misc'
        arxiv = {'cachola_etal_2026_information_satisfaction': '2608.14457'}.get(key, item['url'].rsplit('/', 1)[-1])
        fields.update(howpublished='arXiv preprint arXiv:' + arxiv, url='https://arxiv.org/abs/' + arxiv)
    elif key == 'simon1971attention':
        kind = 'misc'
        fields.update(howpublished='Archival manuscript, Carnegie Mellon University', url=item['url'])
    elif key in {'bucinca2021', 'vasconcelos2023'}:
        kind = 'article'
        volume, article = ('5', '188') if key == 'bucinca2021' else ('7', '129')
        fields.update(journal='Proceedings of the ACM on Human-Computer Interaction', volume=volume, number='CSCW1', pages=article, doi=item['doi'])
    else:
        fields['booktitle'] = bib_escape(venue)
        if item['pages']:
            fields['pages'] = item['pages'].replace('–', '--').replace('-', '--') if '–' not in item['pages'] else item['pages'].replace('–', '--')
        if item['doi']:
            fields['doi'] = item['doi']
        fields['url'] = item['url']
    return '@' + kind + '{' + key + ',\n' + ',\n'.join('  ' + k + ' = {' + v + '}' for k, v in fields.items()) + '\n}'


def build():
    sources = load_sources()
    (ROOT / 'paper/references.bib').write_text('% Generated by scripts/build_bibliography.py; metadata verified in source ledgers.\n\n' + '\n\n'.join(bib_entry(x) for x in sources) + '\n')
    (ROOT / 'research/sources.json').write_text(json.dumps({
        'schema_version': '0.3', 'research_date': '2026-10-25',
        'scope': 'Focused, non-exhaustive review: 17 related/evaluation studies and 2 foundations. Access does not imply whole-paper reading.',
        'source_count': len(sources), 'sources': sources,
    }, ensure_ascii=False, indent=2) + '\n')
    refs = ['# References', 'Generated from the curated source ledgers; version and access limits remain in those ledgers.']
    for number, item in enumerate(sources, 1):
        refs.append(f"{number}. {', '.join(item['authors'])}. {item['year']}. **{item['title']}**. {item['venue']}. [Canonical record]({item['url']}).")
    (ROOT / 'paper/REFERENCES.md').write_text('\n\n'.join(refs) + '\n')
    manuscript = ROOT / 'paper/manuscript.md'
    marker = '<!-- GENERATED-REFERENCES -->'
    body = manuscript.read_text().split(marker)[0].rstrip()
    manuscript.write_text(body + '\n\n' + marker + '\n\n## References\n\n' + '\n\n'.join(refs[2:]) + '\n')
    print(f'Built bibliography and ledgers for {len(sources)} primary sources.')


if __name__ == '__main__':
    build()
